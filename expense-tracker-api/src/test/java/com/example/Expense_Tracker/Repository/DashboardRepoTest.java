package com.example.Expense_Tracker.Repository;

import com.example.Expense_Tracker.entity.Expense;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;
import org.springframework.boot.jdbc.test.autoconfigure.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;

import java.math.BigDecimal;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

@JdbcTest
@AutoConfigureTestDatabase(
        replace = AutoConfigureTestDatabase.Replace.NONE
)
@ActiveProfiles("test")
@Import(DashboardRepo.class)
class DashboardRepoTest {

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private DashboardRepo dashboardRepo;

    @BeforeEach
    void setUp() {
        jdbcTemplate.execute("DROP TABLE IF EXISTS expenses");
        jdbcTemplate.execute("DROP TABLE IF EXISTS income");
        jdbcTemplate.execute("DROP TABLE IF EXISTS categories");

        jdbcTemplate.execute("""
                CREATE TABLE categories (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT,
                    name VARCHAR(50) NOT NULL,
                    type VARCHAR(20) NOT NULL,
                    icon VARCHAR(50),
                    is_custom BOOLEAN DEFAULT FALSE
                )
                """);

        jdbcTemplate.execute("""
                CREATE TABLE income (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    category_id BIGINT NOT NULL,
                    amount DECIMAL(12, 2) NOT NULL,
                    income_date DATE NOT NULL,
                    title VARCHAR(150) NOT NULL,
                    source VARCHAR(100),
                    description TEXT,
                    created_date TIMESTAMP WITH TIME ZONE NOT NULL,
                    updated_date TIMESTAMP WITH TIME ZONE
                )
                """);

        jdbcTemplate.execute("""
                CREATE TABLE expenses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    category_id BIGINT NOT NULL,
                    amount DECIMAL(12, 2) NOT NULL,
                    payment_mode VARCHAR(30) NOT NULL,
                    expense_date DATE NOT NULL,
                    title VARCHAR(150) NOT NULL,
                    description VARCHAR(255),
                    created_at TIMESTAMP WITH TIME ZONE,
                    updated_at TIMESTAMP WITH TIME ZONE
                )
                """);

        jdbcTemplate.update("""
                INSERT INTO categories (id, user_id, name, type)
                VALUES (1, 1, 'Food', 'EXPENSE'),
                       (2, 1, 'Transport', 'EXPENSE'),
                       (3, 2, 'Shopping', 'EXPENSE')
                """);

        jdbcTemplate.update("""
                INSERT INTO income
                    (user_id, category_id, amount, income_date, title, created_date)
                VALUES
                    (1, 1, 50000.00, DATE '2026-10-01', 'Salary',
                     CURRENT_TIMESTAMP),
                    (1, 1, 5000.00, DATE '2026-10-05', 'Freelance',
                     CURRENT_TIMESTAMP),
                    (2, 3, 30000.00, DATE '2026-10-01', 'Other salary',
                     CURRENT_TIMESTAMP)
                """);

        jdbcTemplate.update("""
                INSERT INTO expenses
                    (user_id, category_id, amount, payment_mode,
                     expense_date, title)
                VALUES
                    (1, 1, 500.00, 'UPI', DATE '2026-10-01', 'Groceries'),
                    (1, 1, 300.00, 'CASH', DATE '2026-10-02', 'Lunch'),
                    (1, 2, 200.00, 'UPI', DATE '2026-10-03', 'Bus'),
                    (1, 2, 100.00, 'CREDIT_CARD',
                     DATE '2026-10-04', 'Taxi'),
                    (2, 3, 900.00, 'UPI', DATE '2026-10-01', 'Shopping')
                """);
    }

    @Test
    void getTotalIncome_shouldReturnTotalForUser() {
        BigDecimal total = dashboardRepo.getTotalIncome(1L);

        assertThat(total).isEqualByComparingTo("55000.00");
    }

    @Test
    void getTotalIncome_shouldReturnZeroWhenUserHasNoIncome() {
        BigDecimal total = dashboardRepo.getTotalIncome(99L);

        assertThat(total).isEqualByComparingTo("0");
    }

    @Test
    void getTotalExpense_shouldReturnTotalForUser() {
        BigDecimal total = dashboardRepo.getTotalExpense(1L);

        assertThat(total).isEqualByComparingTo("1100.00");
    }

    @Test
    void getTotalExpense_shouldReturnZeroWhenUserHasNoExpenses() {
        BigDecimal total = dashboardRepo.getTotalExpense(99L);

        assertThat(total).isEqualByComparingTo("0");
    }

    @Test
    void getExpenseByCategory_shouldReturnCorrectTotalsInDescendingOrder() {
        List<DashboardRepo.CategoryExpenseProjection> results =
                dashboardRepo.getExpenseByCategory(1L);

        assertThat(results).hasSize(2);

        assertThat(results.get(0).getCategoryName())
                .isEqualTo("Food");
        assertThat(results.get(0).getAmount())
                .isEqualByComparingTo("800.00");

        assertThat(results.get(1).getCategoryName())
                .isEqualTo("Transport");
        assertThat(results.get(1).getAmount())
                .isEqualByComparingTo("300.00");
    }

    @Test
    void getExpenseByCategory_shouldExcludeOtherUsersExpenses() {
        List<DashboardRepo.CategoryExpenseProjection> results =
                dashboardRepo.getExpenseByCategory(1L);

        assertThat(results)
                .extracting(
                        DashboardRepo.CategoryExpenseProjection::getCategoryName
                )
                .containsExactly("Food", "Transport")
                .doesNotContain("Shopping");
    }

    @Test
    void getExpenseByCategory_shouldReturnEmptyListWhenNoExpensesExist() {
        List<DashboardRepo.CategoryExpenseProjection> results =
                dashboardRepo.getExpenseByCategory(99L);

        assertThat(results).isEmpty();
    }

    @Test
    void getExpenseByPaymentMode_shouldReturnCorrectTotalsInDescendingOrder() {
        List<DashboardRepo.PaymentModeProjection> results =
                dashboardRepo.getExpenseByPaymentMode(1L);

        assertThat(results).hasSize(3);

        assertThat(results.get(0).getPaymentMode())
                .isEqualTo(Expense.PaymentMode.UPI);
        assertThat(results.get(0).getAmount())
                .isEqualByComparingTo("700.00");

        assertThat(results.get(1).getPaymentMode())
                .isEqualTo(Expense.PaymentMode.CASH);
        assertThat(results.get(1).getAmount())
                .isEqualByComparingTo("300.00");

        assertThat(results.get(2).getPaymentMode())
                .isEqualTo(Expense.PaymentMode.CREDIT_CARD);
        assertThat(results.get(2).getAmount())
                .isEqualByComparingTo("100.00");
    }

    @Test
    void getExpenseByPaymentMode_shouldExcludeOtherUsersExpenses() {
        List<DashboardRepo.PaymentModeProjection> results =
                dashboardRepo.getExpenseByPaymentMode(1L);

        assertThat(results)
                .extracting(
                        DashboardRepo.PaymentModeProjection::getPaymentMode
                )
                .containsExactly(
                        Expense.PaymentMode.UPI,
                        Expense.PaymentMode.CASH,
                        Expense.PaymentMode.CREDIT_CARD
                );
    }

    @Test
    void getExpenseByPaymentMode_shouldReturnEmptyListWhenNoExpensesExist() {
        List<DashboardRepo.PaymentModeProjection> results =
                dashboardRepo.getExpenseByPaymentMode(99L);

        assertThat(results).isEmpty();
    }
}